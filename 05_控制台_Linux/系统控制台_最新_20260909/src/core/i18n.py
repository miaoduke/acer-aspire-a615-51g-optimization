"""
src/core/i18n.py — P2-1: 国际化框架（gettext）

P2-1 实施: 极简 i18n 框架
  - 支持中/英双语
  - gettext 标准接口
  - 翻译文件自动 fallback
  - 运行时切换 locale

使用:
  from src.core.i18n import _
  print(_("Profile 配置"))  # → "Profile 配置" (zh) / "Profile Configuration" (en)
"""
import gettext
import locale
import os
from pathlib import Path

# 默认 locale（自动探测）
DEFAULT_LOCALE = "zh_CN"

# 翻译文件目录
LOCALE_DIR = Path(__file__).parent.parent.parent / "locales"


class I18n:
    """国际化单例"""

    _instance = None
    _current_locale = None

    def __init__(self, domain="system-console", localedir=None):
        self.domain = domain
        self.localedir = str(localedir or LOCALE_DIR)
        self.translations = {}

    @classmethod
    def get(cls):
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def set_locale(self, locale_name):
        """切换语言"""
        self._current_locale = locale_name
        try:
            trans = gettext.translation(
                self.domain,
                localedir=self.localedir,
                languages=[locale_name],
                fallback=True,
            )
            self.translations[locale_name] = trans
        except FileNotFoundError:
            # 翻译文件不存在，用 null translation
            self.translations[locale_name] = gettext.NullTranslations()

    def gettext(self, msg):
        """翻译单条消息"""
        if self._current_locale is None:
            # 自动探测
            try:
                sys_locale = locale.getlocale()[0] or DEFAULT_LOCALE
                self.set_locale(sys_locale)
            except Exception:
                self.set_locale(DEFAULT_LOCALE)

        trans = self.translations.get(self._current_locale)
        if trans is None:
            return msg
        return trans.gettext(msg)

    def ngettext(self, singular, plural, n):
        """复数形式翻译"""
        if self._current_locale is None:
            return singular if n == 1 else plural
        trans = self.translations.get(self._current_locale)
        if trans is None:
            return singular if n == 1 else plural
        return trans.ngettext(singular, plural, n)


# 全局 _ 函数
def T(msg):
    """翻译快捷函数"""
    return I18n.get().gettext(msg)


def set_locale(locale_name):
    """设置语言（zh_CN / en_US）"""
    I18n.get().set_locale(locale_name)


