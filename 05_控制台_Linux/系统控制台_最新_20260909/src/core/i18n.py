def translate(msg, locale_name=None):
    """直接用翻译字典（fallback）"""
    if locale_name is None:
        locale_name = I18n.get()._current_locale or DEFAULT_LOCALE
    return _TRANSLATIONS.get(locale_name, {}).get(msg, msg)


def _smart(msg):
    """智能翻译：优先用 gettext 翻译文件，回退到内置字典"""
    try:
        i18n = I18n.get()
        result = i18n.gettext(msg)
        # 如果 gettext 返回原 msg（翻译文件未加载），用内置字典
        if result == msg:
            return translate(msg)
        return result
    except Exception:
        return msg


